import org.jetbrains.kotlin.gradle.dsl.JvmTarget
import java.io.ByteArrayOutputStream
import javax.inject.Inject

// Conformance tests for protoc-gen-protomorphic: the test protos here cover every field type, proto3
// and editions presence, packing, oneofs, maps, well-known types, unknown fields and enums,
// interfaces and extensions. Tests compare the generated code's encoding with `protoc --encode`,
// protobuf's reference encoder, on JVM, iOS and Android. The module applies the protomorphic plugin
// like any consumer, using this build's generator and runtime.
plugins {
    alias(libs.plugins.kotlinMultiplatform)
    alias(libs.plugins.androidMultiplatformLibrary)
    id("com.dabble.protomorphic")
}

protomorphic {
    useLocalProjects = true
}

/** Encodes each `<Name>.<message.type>.txtpb` with `protoc --encode` into a hex constant in `Goldens`. */
abstract class EncodeGoldens @Inject constructor(
    private val exec: ExecOperations,
    private val fileSystem: FileSystemOperations,
    private val archives: ArchiveOperations,
) : DefaultTask() {
    @get:InputFiles @get:PathSensitive(PathSensitivity.NONE) abstract val protoc: ConfigurableFileCollection
    @get:InputFiles @get:PathSensitive(PathSensitivity.NONE) abstract val wellKnownProtos: ConfigurableFileCollection
    @get:InputFiles @get:PathSensitive(PathSensitivity.RELATIVE) abstract val protoRoots: ConfigurableFileCollection
    @get:InputDirectory @get:PathSensitive(PathSensitivity.RELATIVE) abstract val textprotos: DirectoryProperty
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun encode() {
        val work = temporaryDir
        val wellKnown = work.resolve("well-known")
        fileSystem.delete { delete(wellKnown) }
        fileSystem.copy {
            from(archives.zipTree(wellKnownProtos.singleFile)) { include("google/protobuf/*.proto") }
            into(wellKnown)
        }
        val protocExe = work.resolve("protoc").also { protoc.singleFile.copyTo(it, overwrite = true); it.setExecutable(true) }
        val roots = protoRoots.files.toList()
        val ownRoot = roots.first()
        val protos = ownRoot.walkTopDown().filter { it.extension == "proto" }
            .map { it.relativeTo(ownRoot).invariantSeparatorsPath }.sorted().toList()

        val constants = textprotos.get().asFile.listFiles()!!.filter { it.name.endsWith(".txtpb") }.sortedBy { it.name }
            .map { file ->
                val name = file.name.substringBefore('.')
                val type = file.name.removePrefix("$name.").removeSuffix(".txtpb")
                val bytes = ByteArrayOutputStream()
                file.inputStream().use { input ->
                    exec.exec {
                        commandLine(
                            listOf(protocExe.absolutePath, "--encode=$type") +
                                roots.map { "-I${it.absolutePath}" } + "-I${wellKnown.absolutePath}" + protos,
                        )
                        standardInput = input
                        standardOutput = bytes
                    }
                }
                val hex = bytes.toByteArray().joinToString("") { "%02x".format(it) }
                "  /** `protoc --encode=$type` of ${file.name}. */\n  const val $name: String = \"$hex\""
            }
        val out = outputDir.get().asFile
        fileSystem.delete { delete(out) }
        out.mkdirs()
        out.resolve("Goldens.kt").writeText(
            "// Generated by :conformance:encodeGoldens. Do not edit.\n" +
                "package com.dabble.protomorphic.conformance\n\nobject Goldens {\n" +
                constants.joinToString("\n") + "\n}\n",
        )
    }
}

val encodeGoldens by tasks.registering(EncodeGoldens::class) {
    protoc.from(configurations.named("protomorphicProtoc"))
    wellKnownProtos.from(configurations.named("protomorphicWellKnownProtos"))
    protoRoots.from("src/commonMain/proto", rootProject.file("gradle-plugin/src/main/resources"))
    textprotos = layout.projectDirectory.dir("src/test-data")
    outputDir = layout.buildDirectory.dir("generated/goldens")
}

