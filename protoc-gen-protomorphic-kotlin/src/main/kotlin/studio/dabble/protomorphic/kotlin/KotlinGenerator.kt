package studio.dabble.protomorphic.kotlin

import studio.dabble.protomorphic.rules.Schema
import studio.dabble.protomorphic.rules.SchemaException
import com.google.protobuf.Descriptors.Descriptor
import com.google.protobuf.Descriptors.EnumDescriptor
import com.google.protobuf.Descriptors.FieldDescriptor
import com.google.protobuf.Descriptors.FieldDescriptor.Type
import com.google.protobuf.Descriptors.FileDescriptor
import com.google.protobuf.Descriptors.OneofDescriptor

/**
 * Generates one Kotlin file per .proto file:
 * - a `data class` per message with a companion `ADAPTER` (a Wire [com.squareup.wire.ProtoAdapter]),
 *   nested messages and enums as nested declarations, and a sealed interface per `oneof`;
 * - an `enum class` (a [com.squareup.wire.WireEnum]) with an `ADAPTER` per enum;
 * - for `(interface)` messages, a nested `Implementation` interface whose properties are the
 *   interface's (abstract) fields, which each implementation's data class overrides, and whose type
 *   parameters are the interface's abstract nested types (`Implementation<Input, Output>`), bound
 *   by each implementation to its own nested messages of the same names;
 * - for each `extend` field, an [studio.dabble.protomorphic.ProtoExtension] in the file's
 *   `<File>Extensions` object and typed Kotlin accessors on the extended class.
 *
 * Semantics come from protobuf-java's resolved descriptors, so proto3 and editions behave per
 * spec: implicit-presence scalars are non-null with their zero default and are not written when
 * zero; explicit-presence fields are nullable; repeated scalars are packed unless a feature says
 * EXPANDED; unknown enum values and unknown fields are preserved.
 *
 * All references are fully qualified, so generated files need no imports and cannot clash with
 * schema type names.
 */
class KotlinGenerator(private val schema: Schema) {

    data class Output(val path: String, val content: String)

    fun generate(file: FileDescriptor): Output {
        val pkg = kotlinPackage(file)
        if (pkg.isEmpty()) throw SchemaException("${file.name}: needs a package or java_package")
        val context = FileContext(file)
        val w = CodeWriter()
        w.line("// Code generated by protoc-gen-protomorphic-kotlin. Do not edit.")
        w.line("// Source: ${file.name}")
        w.line("@file:Suppress(\"RedundantVisibilityModifier\", \"unused\", \"RemoveRedundantQualifierName\")")
        w.line()
        w.line("package $pkg")
        file.enumTypes.forEach { enum(w, context, it, listOf(5, it.index)) }
        file.messageTypes.forEach { message(w, context, it, listOf(4, it.index)) }
        extensions(w, context)
        return Output(pkg.replace('.', '/') + "/" + context.fileStem + ".kt", w.toString())
    }

    /** Per-file facts: the extensions declared here, and which messages implement interfaces. */
    private inner class FileContext(val file: FileDescriptor) {
        val fileStem = upperCamel(file.name.substringAfterLast('/').removeSuffix(".proto"))
        val extensionsObject = kotlinPackage(file) + "." + fileStem + "Extensions"

        val extensions: List<FieldDescriptor> =
            (file.extensions + allMessages(file).flatMap { it.extensions }).filterNot { schema.isOptionExtension(it) }

        /** Implementation message full name -> the interface extensions it is the value of. */
        val implementations: Map<String, List<FieldDescriptor>> = extensions
            .filter { schema.isInterface(it.containingType) && it.type == Type.MESSAGE && it.messageType.file == file }
            .groupBy { it.messageType.fullName }

        /** Scoped extensions get a nested object per scope, so same-named ones do not clash. */
        fun holder(ext: FieldDescriptor) = extensionsObject + (ext.extensionScope?.let { ".${it.name}" } ?: "")

        fun extensionRef(ext: FieldDescriptor) = "${holder(ext)}.${extensionProperty(ext)}"
    }

    // ----- Enums --------------------------------------------------------------------------------

    private fun enum(w: CodeWriter, context: FileContext, enum: EnumDescriptor, path: List<Int>) {
        val name = enum.name
        val self = kotlinName(enum)
        w.line()
        w.kdoc(schema.comment(context.file, path))
        w.block("public enum class $name(override val `value`: kotlin.Int) : com.squareup.wire.WireEnum") {
            enum.values.forEach { value ->
                w.kdoc(schema.comment(context.file, path + listOf(2, value.index)))
                deprecated(w, value.options.deprecated)
                w.line("${escape(value.name)}(${value.number}),")
            }
            w.line(";")
            w.line()
            w.block("public companion object") {
                val byNumber = enum.values.distinctBy { it.number }
                w.block("public fun fromValue(`value`: kotlin.Int): $self? = when (`value`)") {
                    byNumber.forEach { w.line("${it.number} -> ${escape(it.name)}") }
                    w.line("else -> null")
                }
                w.line()
                val identity = enum.values.firstOrNull { it.number == 0 }?.let { "$self.${escape(it.name)}" } ?: "null"
                w.line("public val ADAPTER: com.squareup.wire.ProtoAdapter<$self> = object : com.squareup.wire.EnumAdapter<$self>(")
                w.line("  $self::class, com.squareup.wire.Syntax.PROTO_3, $identity,")
                w.block(")") {
                    w.line("override fun fromValue(`value`: kotlin.Int): $self? = $self.fromValue(`value`)")
                }
            }
        }
    }

    // ----- Messages -----------------------------------------------------------------------------

    private fun message(w: CodeWriter, context: FileContext, message: Descriptor, path: List<Int>) {
        if (message.options.mapEntry) return
        val file = context.file
        val name = message.name
        val self = kotlinName(message)
        val isInterface = schema.isInterface(message)
        val abstract = if (isInterface) message.fields.map { Prop(it) } else emptyList()
        val props = if (isInterface) emptyList() else message.fields.filter { it.realContainingOneof == null }.map { Prop(it) }
        val oneofs = if (isInterface) emptyList() else message.realOneofs.map { Oneof(message, it) }
        val implemented = context.implementations[message.fullName].orEmpty()
        val overridden = implemented.flatMap { ext -> ext.containingType.fields.map { it.name } }.toSet()
        val abstractTypes = if (isInterface) message.nestedTypes.filterNot { it.options.mapEntry } else emptyList()

        // Constructor parameters in declaration order; a oneof sits where its first field is.
        val parameters: List<Any> = message.fields.mapNotNull { field ->
            val oneof = field.realContainingOneof
            when {
                isInterface -> null
                oneof == null -> props.first { it.field == field }
                oneof.fields.first() == field -> oneofs.first { it.descriptor == oneof }
                else -> null
            }
        }

        w.line()
        w.kdoc(schema.comment(file, path))
        deprecated(w, message.options.deprecated)
        w.line("public data class $name(")
        parameters.forEach { p ->
            when (p) {
                is Prop -> {
                    w.kdoc(schema.comment(file, path + listOf(2, p.field.index)))
                    deprecated(w, p.field.options.deprecated)
                    val modifier = if (p.field.name in overridden) "override" else "public"
                    w.line("  $modifier val ${p.property}: ${p.type} = ${p.default},")
                }
                is Oneof -> {
                    w.kdoc(schema.comment(file, path + listOf(8, p.descriptor.index)))
                    w.line("  public val ${p.property}: $self.${p.typeName}? = null,")
                }
            }
        }
        w.line("  public val unknownFields: okio.ByteString = okio.ByteString.EMPTY,")
        val supertypes = implemented.map { ext ->
            val types = ext.containingType.nestedTypes.filterNot { it.options.mapEntry }
            "${kotlinName(ext.containingType)}.Implementation" +
                if (types.isEmpty()) "" else types.joinToString(prefix = "<", postfix = ">") { "$self.${it.name}" }
        }.distinct()
        w.block(")" + if (supertypes.isEmpty()) "" else " : " + supertypes.joinToString()) {
            implemented.distinctBy { it.containingType.fullName }.forEach { ext ->
                val iface = kotlinName(ext.containingType)
                w.line("override fun to${ext.containingType.name}(): $iface =")
                w.line("  $iface(unknownFields = studio.dabble.protomorphic.ProtoExtensions.only(${context.extensionRef(ext)}, this))")
                w.line()
            }
            if (isInterface) {
                w.line("/** Implemented by each message declared as an implementation of [$name] in the same file as its extension. */")
                val typeParameters = if (abstractTypes.isEmpty()) "" else abstractTypes.joinToString(prefix = "<", postfix = ">") { "${it.name} : kotlin.Any" }
                w.block("public interface Implementation$typeParameters") {
                    abstract.forEach { p ->
                        w.kdoc(schema.comment(file, path + listOf(2, p.field.index)))
                        deprecated(w, p.field.options.deprecated)
                        val type = abstractTypes.fold(p.type) { t, abstractType -> t.replace(kotlinName(abstractType), abstractType.name) }
                        w.line("public val ${p.property}: $type")
                        w.line()
                    }
                    w.line("public fun to$name(): $self")
                }
                w.line()
                val skipped = if (abstract.isEmpty()) "" else ", kotlin.collections.setOf(" + abstract.joinToString { it.field.number.toString() } + ")"
                w.line("/** Field number of the implementation this value holds, or null when it holds none. */")
                w.line("public val implementationNumber: kotlin.Int?")
                w.line("  get() = studio.dabble.protomorphic.ProtoExtensions.firstNumber(unknownFields$skipped)")
                w.line()
            }
            oneofs.forEach { oneofType(w, file, path, self, it) }
            message.enumTypes.forEach { enum(w, context, it, path + listOf(4, it.index)) }
            if (!isInterface) message.nestedTypes.forEach { message(w, context, it, path + listOf(3, it.index)) }
            w.line()
            w.block("public companion object") {
                adapter(w, message, self, props, oneofs, isInterface)
            }
        }
    }

    private fun oneofType(w: CodeWriter, file: FileDescriptor, path: List<Int>, self: String, oneof: Oneof) {
        w.kdoc(schema.comment(file, path + listOf(8, oneof.descriptor.index)))
        w.block("public sealed interface ${oneof.typeName}") {
            oneof.cases.forEach { case ->
                w.kdoc(schema.comment(file, path + listOf(2, case.field.index)))
                w.line("public data class ${case.className}(public val `value`: ${case.valueType}) : $self.${oneof.typeName}")
            }
        }
        w.line()
    }

    private fun adapter(w: CodeWriter, message: Descriptor, self: String, props: List<Prop>, oneofs: List<Oneof>, isInterface: Boolean) {
        val ordered: List<Member> = (props + oneofs.flatMap { it.cases }).sortedBy { it.field.number }
        w.line("public val ADAPTER: studio.dabble.protomorphic.MessageAdapter<$self> = object : studio.dabble.protomorphic.MessageAdapter<$self>(")
        w.line("  com.squareup.wire.FieldEncoding.LENGTH_DELIMITED, $self::class,")
        w.line("  \"type.googleapis.com/${message.fullName}\", com.squareup.wire.Syntax.PROTO_3, null, \"${message.file.name}\",")
        w.block(")") {
            props.filter { it.kind == Kind.REPEATED || it.kind == Kind.MAP }.forEach {
                w.line("private val ${it.property.trim('`')}Adapter by lazy { ${it.collectionAdapter} }")
            }
            w.line()
            val fields = if (isInterface) emptyList() else message.fields
            w.line("override val fields: kotlin.collections.Map<kotlin.String, studio.dabble.protomorphic.ProtoField> by lazy {")
            w.line("  kotlin.collections.mapOf(")
            fields.forEach { f ->
                val nested = f.type == Type.MESSAGE && !f.isRepeated && wellKnown[f.messageType.fullName] == null
                val message = if (nested) ", messageAdapter = { ${kotlinName(f.messageType)}.ADAPTER }" else ""
                val repeated = if (f.isRepeated) ", repeated = true" else ""
                w.line("    \"${f.name}\" to studio.dabble.protomorphic.ProtoField(${f.number}, com.squareup.wire.FieldEncoding.${encoding(f)}$repeated$message),")
            }
            w.line("  )")
            w.line("}")
            w.line()
            w.block("override fun encodedSize(`value`: $self): kotlin.Int") {
                w.line("var size = value.unknownFields.size")
                ordered.forEach { m -> w.line(m.guard("size += ${m.adapterRef}.encodedSizeWithTag(${m.field.number}, ${m.valueExpr})")) }
                w.line("return size")
            }
            w.line()
            w.block("override fun encode(writer: com.squareup.wire.ProtoWriter, `value`: $self)") {
                ordered.forEach { m -> w.line(m.guard("${m.adapterRef}.encodeWithTag(writer, ${m.field.number}, ${m.valueExpr})")) }
                w.line("writer.writeBytes(value.unknownFields)")
            }
            w.line()
            w.block("override fun decode(reader: com.squareup.wire.ProtoReader): $self") {
                props.forEach { w.line(it.local) }
                oneofs.forEach { w.line("var ${it.localName}: $self.${it.typeName}? = null") }
                w.block("val unknownFields = reader.forEachTag", open = "{ tag ->") {
                    w.block("when (tag)") {
                        ordered.forEach { m -> w.line("${m.field.number} -> ${m.decode}") }
                        w.line("else -> reader.readUnknownField(tag)")
                    }
                }
                w.line("return $self(")
                props.forEach { w.line("  ${it.property} = ${it.localName},") }
                oneofs.forEach { w.line("  ${it.property} = ${it.localName},") }
                w.line("  unknownFields = unknownFields,")
                w.line(")")
            }
            w.line()
            w.line("override fun redact(`value`: $self): $self = value")
        }
    }

    // ----- Extensions ---------------------------------------------------------------------------

    private fun extensions(w: CodeWriter, context: FileContext) {
        if (context.extensions.isEmpty()) return
        context.extensions.forEach { ext ->
            if (ext.isRepeated) throw SchemaException("${ext.fullName}: repeated extensions are not supported")
            if (ext.containingType.file.`package`.startsWith("google.protobuf")) {
                throw SchemaException("${ext.fullName}: extending ${ext.containingType.fullName} is not supported")
            }
        }
        context.extensions.groupBy { it.extensionScope?.name }.forEach { (scope, group) ->
            if (scope != null && group.map { it.extensionScope }.distinct().size > 1) {
                throw SchemaException("${context.file.name}: extensions are declared in two messages named $scope; rename one")
            }
        }
        context.extensions.groupBy { it.containingType.fullName to it.name }.values.filter { it.size > 1 }.forEach { same ->
            throw SchemaException(
                "${context.file.name}: ${same.joinToString { it.fullName }} extend ${same.first().containingType.fullName} " +
                    "with the same name, so their Kotlin accessors would clash",
            )
        }
        val objectName = context.extensionsObject.substringAfterLast('.')
        fun declare(ext: FieldDescriptor) {
            w.kdoc(extensionComment(context, ext))
            w.line("public val ${extensionProperty(ext)}: studio.dabble.protomorphic.ProtoExtension<${valueType(ext)}> =")
            w.line("  studio.dabble.protomorphic.ProtoExtension(\"${ext.containingType.fullName}\", ${ext.number}, \"${ext.fullName}\", ${adapterOf(ext)})")
            w.line()
        }
        w.line()
        w.line("/** The extensions declared in ${context.file.name}. */")
        w.block("public object $objectName") {
            context.extensions.filter { it.extensionScope == null }.forEach { declare(it) }
            context.extensions.filter { it.extensionScope != null }.groupBy { it.extensionScope.name }.forEach { (scope, group) ->
                w.line("/** The extensions declared inside message $scope. */")
                w.block("public object $scope") {
                    group.forEach { declare(it) }
                }
                w.line()
            }
            w.line("/** Every extension in this file. */")
            w.line("public val all: kotlin.collections.List<studio.dabble.protomorphic.ProtoExtension<*>> by lazy {")
            w.line("  kotlin.collections.listOf(" + context.extensions.joinToString { context.extensionRef(it) } + ")")
            w.line("}")
        }
        context.extensions.forEach { ext ->
            val extendee = kotlinName(ext.containingType)
            val value = valueType(ext)
            val property = extensionProperty(ext)
            val ref = context.extensionRef(ext)
            w.line()
            w.kdoc(extensionComment(context, ext))
            w.line("public val $extendee.$property: $value?")
            w.line("  get() = studio.dabble.protomorphic.ProtoExtensions.get(unknownFields, $ref)")
            w.line()
            if (schema.isInterface(ext.containingType)) {
                w.line("/** A [$extendee] holding [value] as its implementation. */")
                w.line("public fun $extendee.Companion.$property(`value`: $value): $extendee =")
                w.line("  $extendee(unknownFields = studio.dabble.protomorphic.ProtoExtensions.only($ref, `value`))")
            } else {
                w.line("/** This value with the [$property] extension set to [value]. */")
                w.line("public fun $extendee.with${upperCamel(ext.name)}(`value`: $value): $extendee =")
                w.line("  copy(unknownFields = studio.dabble.protomorphic.ProtoExtensions.set(unknownFields, $ref, `value`))")
            }
        }
    }

    private fun extensionComment(context: FileContext, ext: FieldDescriptor): String {
        val path = ext.extensionScope?.let { scope -> messagePath(scope) + listOf(6, ext.index) } ?: listOf(7, ext.index)
        val own = schema.comment(context.file, path)?.trimEnd()
        val what = "Extension ${ext.number} of `${ext.containingType.fullName}`."
        return if (own.isNullOrBlank()) what else "$own\n\n$what"
    }

    private fun messagePath(message: Descriptor): List<Int> =
        message.containingType?.let { messagePath(it) + listOf(3, message.index) } ?: listOf(4, message.index)

    private fun extensionProperty(ext: FieldDescriptor) = escape(lowerCamel(ext.name))

    private fun valueType(ext: FieldDescriptor): String = elementType(ext).removeSuffix("?")

    private fun adapterOf(ext: FieldDescriptor): String = scalarAdapter(ext)

    // ----- Fields -------------------------------------------------------------------------------

    private enum class Kind { IMPLICIT, NULLABLE, REPEATED, MAP }

    /** A field encoded in the message's adapter: a regular property or a oneof case. */
    private interface Member {
        val field: FieldDescriptor
        val adapterRef: String
        val valueExpr: String
        val decode: String
        fun guard(statement: String): String
    }

    private inner class Prop(override val field: FieldDescriptor) : Member {
        val property = propertyName(field.name)
        val localName = "v_" + property.trim('`')

        val kind = when {
            field.isMapField -> Kind.MAP
            field.isRepeated -> Kind.REPEATED
            field.type == Type.MESSAGE || field.hasPresence() -> Kind.NULLABLE
            else -> Kind.IMPLICIT
        }

        init {
            if (field.type == Type.GROUP) throw SchemaException("${field.fullName}: groups are not supported")
            if (field.isRequired) throw SchemaException("${field.fullName}: required fields are not supported")
            if (field.toProto().hasDefaultValue()) {
                throw SchemaException("${field.fullName}: custom default values are not supported")
            }
        }

        private val mapKey get() = field.messageType.findFieldByNumber(1)
        private val mapValue get() = field.messageType.findFieldByNumber(2)

        val type: String = when (kind) {
            Kind.MAP -> "kotlin.collections.Map<${elementType(mapKey)}, ${elementType(mapValue)}>"
            Kind.REPEATED -> "kotlin.collections.List<${elementType(field)}>"
            Kind.NULLABLE -> elementType(field).let { if (it.endsWith("?")) it else "$it?" }
            Kind.IMPLICIT -> elementType(field)
        }

        val default: String = when (kind) {
            Kind.MAP -> "kotlin.collections.emptyMap()"
            Kind.REPEATED -> "kotlin.collections.emptyList()"
            Kind.NULLABLE -> "null"
            Kind.IMPLICIT -> zeroValue(field)
        }

        val collectionAdapter: String by lazy {
            val f = this@Prop.field
            when (kind) {
                Kind.MAP -> "com.squareup.wire.ProtoAdapter.newMapAdapter(${scalarAdapter(mapKey)}, ${scalarAdapter(mapValue)})"
                Kind.REPEATED -> scalarAdapter(f) + if (f.isPacked) ".asPacked()" else ".asRepeated()"
                else -> error("not a collection")
            }
        }

        override val adapterRef: String =
            if (kind == Kind.MAP || kind == Kind.REPEATED) property.trim('`') + "Adapter" else scalarAdapter(field)

        override val valueExpr = "value.$property"

        override fun guard(statement: String): String = when {
            kind == Kind.IMPLICIT -> "if (${nonDefault(field, valueExpr)}) $statement"
            // Wire writes a null Value as NullValue, but here null means the field is unset.
            kind == Kind.NULLABLE && field.type == Type.MESSAGE && field.messageType.fullName == "google.protobuf.Value" ->
                "if ($valueExpr != null) $statement"
            else -> statement
        }

        val local: String = when (kind) {
            Kind.MAP -> "val $localName = kotlin.collections.mutableMapOf<${elementType(mapKey)}, ${elementType(mapValue)}>()"
            Kind.REPEATED -> "val $localName = kotlin.collections.mutableListOf<${elementType(field)}>()"
            Kind.NULLABLE, Kind.IMPLICIT -> "var $localName: $type = $default"
        }

        override val decode: String = when (kind) {
            Kind.MAP -> "$localName.putAll($adapterRef.decode(reader))"
            // tryDecode handles packed and unpacked scalars, but treats a zero-length value as "no
            // data", so strings, bytes and messages (where empty is a real element) use decode.
            Kind.REPEATED -> if (field.type in LENGTH_DELIMITED) {
                "$localName.add(${scalarAdapter(field)}.decode(reader))"
            } else {
                enumSafe(field, "${scalarAdapter(field)}.tryDecode(reader, $localName)")
            }
            Kind.NULLABLE, Kind.IMPLICIT ->
                if (mergesMessages(field)) "$localName = ${merged(scalarAdapter(field), localName)}"
                else enumSafe(field, "$localName = ${scalarAdapter(field)}.decode(reader)")
        }
    }

    private inner class Oneof(message: Descriptor, val descriptor: OneofDescriptor) {
        val property = propertyName(descriptor.name)
        val localName = "v_" + property.trim('`')
        val typeName: String = upperCamel(descriptor.name).let { base ->
            val taken = message.nestedTypes.map { it.name } + message.enumTypes.map { it.name } + listOf("Implementation", "Companion")
            if (base in taken) base + "Oneof" else base
        }
        val cases = descriptor.fields.map { Case(this, kotlinName(message), it) }
    }

    private inner class Case(val oneof: Oneof, private val self: String, override val field: FieldDescriptor) : Member {
        init {
            if (field.type == Type.GROUP) throw SchemaException("${field.fullName}: groups are not supported")
        }

        val className = upperCamel(field.name)
        val valueType = elementType(field).removeSuffix("?")
        private val caseRef = "$self.${oneof.typeName}.$className"
        override val adapterRef = scalarAdapter(field)
        override val valueExpr = "(value.${oneof.property} as? $caseRef)?.`value`"
        override fun guard(statement: String) = statement
        override val decode =
            if (mergesMessages(field)) "${oneof.localName} = $caseRef(${merged(scalarAdapter(field), "(${oneof.localName} as? $caseRef)?.`value`")})"
            else enumSafe(field, "${oneof.localName} = $caseRef(${scalarAdapter(field)}.decode(reader))")
    }

    private fun encoding(field: FieldDescriptor): String = when (field.type) {
        Type.FIXED32, Type.SFIXED32, Type.FLOAT -> "FIXED32"
        Type.FIXED64, Type.SFIXED64, Type.DOUBLE -> "FIXED64"
        Type.STRING, Type.BYTES, Type.MESSAGE, Type.GROUP -> "LENGTH_DELIMITED"
        else -> "VARINT"
    }

    private fun mergesMessages(field: FieldDescriptor) = field.type == Type.MESSAGE && wellKnown[field.messageType.fullName] == null

    /** Protobuf merges a repeated occurrence of a singular message field into the earlier one. */
    private fun merged(adapter: String, previous: String) =
        "$previous.let { previous -> if (previous == null) $adapter.decode(reader) else " +
            "$adapter.decode(okio.Buffer().write($adapter.encodeByteString(previous)).write(reader.readBytes()).readByteString()) }"

    /** Unknown enum values are kept as unknown fields instead of failing the decode. */
    private fun enumSafe(field: FieldDescriptor, statement: String): String =
        if (field.type != Type.ENUM) {
            statement
        } else {
            "try { $statement } catch (e: com.squareup.wire.ProtoAdapter.EnumConstantNotFoundException) " +
                "{ reader.addUnknownField(tag, com.squareup.wire.FieldEncoding.VARINT, e.value.toLong()) }"
        }

    // ----- Types --------------------------------------------------------------------------------

    private class WellKnown(val type: String, val adapter: String)

    private val wellKnown = mapOf(
        "google.protobuf.Any" to WellKnown("com.squareup.wire.AnyMessage", "com.squareup.wire.AnyMessage.ADAPTER"),
        "google.protobuf.Duration" to WellKnown("com.squareup.wire.Duration", "$ADAPTERS.DURATION"),
        "google.protobuf.Timestamp" to WellKnown("com.squareup.wire.Instant", "$ADAPTERS.INSTANT"),
        "google.protobuf.Empty" to WellKnown("kotlin.Unit", "$ADAPTERS.EMPTY"),
        "google.protobuf.Struct" to WellKnown("kotlin.collections.Map<kotlin.String, *>?", "$ADAPTERS.STRUCT_MAP"),
        "google.protobuf.ListValue" to WellKnown("kotlin.collections.List<*>?", "$ADAPTERS.STRUCT_LIST"),
        "google.protobuf.Value" to WellKnown("kotlin.Any?", "$ADAPTERS.STRUCT_VALUE"),
        "google.protobuf.DoubleValue" to WellKnown("kotlin.Double?", "$ADAPTERS.DOUBLE_VALUE"),
        "google.protobuf.FloatValue" to WellKnown("kotlin.Float?", "$ADAPTERS.FLOAT_VALUE"),
        "google.protobuf.Int64Value" to WellKnown("kotlin.Long?", "$ADAPTERS.INT64_VALUE"),
        "google.protobuf.UInt64Value" to WellKnown("kotlin.Long?", "$ADAPTERS.UINT64_VALUE"),
        "google.protobuf.Int32Value" to WellKnown("kotlin.Int?", "$ADAPTERS.INT32_VALUE"),
        "google.protobuf.UInt32Value" to WellKnown("kotlin.Int?", "$ADAPTERS.UINT32_VALUE"),
        "google.protobuf.BoolValue" to WellKnown("kotlin.Boolean?", "$ADAPTERS.BOOL_VALUE"),
        "google.protobuf.StringValue" to WellKnown("kotlin.String?", "$ADAPTERS.STRING_VALUE"),
        "google.protobuf.BytesValue" to WellKnown("okio.ByteString?", "$ADAPTERS.BYTES_VALUE"),
    )

    /** Like [kotlinName], but protomorphic's runtime declares google.protobuf.NullValue, as nothing generates struct.proto. */
    private fun enumName(enum: EnumDescriptor): String =
        if (enum.fullName == "google.protobuf.NullValue") "studio.dabble.protomorphic.NullValue" else kotlinName(enum)

    /** The Kotlin type of one value of [field] (a list element or map value for collections). */
    private fun elementType(field: FieldDescriptor): String = when (field.type) {
        Type.DOUBLE -> "kotlin.Double"
        Type.FLOAT -> "kotlin.Float"
        Type.INT64, Type.UINT64, Type.FIXED64, Type.SFIXED64, Type.SINT64 -> "kotlin.Long"
        Type.INT32, Type.UINT32, Type.FIXED32, Type.SFIXED32, Type.SINT32 -> "kotlin.Int"
        Type.BOOL -> "kotlin.Boolean"
        Type.STRING -> "kotlin.String"
        Type.BYTES -> "okio.ByteString"
        Type.ENUM -> enumName(field.enumType)
        Type.MESSAGE -> wellKnown[field.messageType.fullName]?.type ?: unsupportedGoogle(field) ?: kotlinName(field.messageType)
        Type.GROUP, null -> throw SchemaException("${field.fullName}: groups are not supported")
    }

    private fun unsupportedGoogle(field: FieldDescriptor): String? {
        if (field.messageType.fullName.startsWith("google.protobuf.")) {
            throw SchemaException("${field.fullName}: ${field.messageType.fullName} is not supported as a field type")
        }
        return null
    }

    /** The adapter of one value of [field]. */
    private fun scalarAdapter(field: FieldDescriptor): String = when (field.type) {
        Type.DOUBLE -> "$ADAPTERS.DOUBLE"
        Type.FLOAT -> "$ADAPTERS.FLOAT"
        Type.INT64 -> "$ADAPTERS.INT64"
        Type.UINT64 -> "$ADAPTERS.UINT64"
        Type.FIXED64 -> "$ADAPTERS.FIXED64"
        Type.SFIXED64 -> "$ADAPTERS.SFIXED64"
        Type.SINT64 -> "$ADAPTERS.SINT64"
        Type.INT32 -> "$ADAPTERS.INT32"
        Type.UINT32 -> "$ADAPTERS.UINT32"
        Type.FIXED32 -> "$ADAPTERS.FIXED32"
        Type.SFIXED32 -> "$ADAPTERS.SFIXED32"
        Type.SINT32 -> "$ADAPTERS.SINT32"
        Type.BOOL -> "studio.dabble.protomorphic.PROTO_BOOL"
        Type.STRING -> "$ADAPTERS.STRING"
        Type.BYTES -> "$ADAPTERS.BYTES"
        Type.ENUM -> enumName(field.enumType) + ".ADAPTER"
        Type.MESSAGE -> wellKnown[field.messageType.fullName]?.adapter ?: (kotlinName(field.messageType) + ".ADAPTER")
        Type.GROUP, null -> throw SchemaException("${field.fullName}: groups are not supported")
    }

    private fun zeroValue(field: FieldDescriptor): String = when (field.type) {
        Type.DOUBLE -> "0.0"
        Type.FLOAT -> "0f"
        Type.INT64, Type.UINT64, Type.FIXED64, Type.SFIXED64, Type.SINT64 -> "0L"
        Type.INT32, Type.UINT32, Type.FIXED32, Type.SFIXED32, Type.SINT32 -> "0"
        Type.BOOL -> "false"
        Type.STRING -> "\"\""
        Type.BYTES -> "okio.ByteString.EMPTY"
        Type.ENUM -> {
            val zero = field.enumType.values.firstOrNull { it.number == 0 }
                ?: throw SchemaException("${field.fullName}: implicit-presence enum ${field.enumType.fullName} needs a value numbered 0")
            enumName(field.enumType) + "." + escape(zero.name)
        }
        else -> throw SchemaException("${field.fullName}: no implicit default for ${field.type}")
    }

    /** Whether an implicit-presence value differs from its default, so it must be written. */
    private fun nonDefault(field: FieldDescriptor, expr: String): String = when (field.type) {
        Type.FLOAT -> "$expr.toRawBits() != 0"
        Type.DOUBLE -> "$expr.toRawBits() != 0L"
        Type.BOOL -> expr
        else -> "$expr != ${zeroValue(field)}"
    }

    // ----- Names --------------------------------------------------------------------------------

    private fun deprecated(w: CodeWriter, deprecated: Boolean) {
        if (deprecated) w.line("@Deprecated(\"Deprecated in the .proto schema.\")")
    }

    private fun propertyName(protoName: String): String {
        val name = lowerCamel(protoName)
        return if (name == "unknownFields") "unknownFields_" else escape(name)
    }

    private fun allMessages(file: FileDescriptor): List<Descriptor> =
        file.messageTypes.flatMap { listOf(it) + nestedMessages(it) }

    private fun nestedMessages(message: Descriptor): List<Descriptor> =
        message.nestedTypes.flatMap { listOf(it) + nestedMessages(it) }

    companion object {
        private const val ADAPTERS = "com.squareup.wire.ProtoAdapter"

        private val LENGTH_DELIMITED = setOf(Type.STRING, Type.BYTES, Type.MESSAGE)

        private val KEYWORDS = setOf(
            "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface",
            "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias",
            "typeof", "val", "var", "when", "while", "value",
        )

        fun escape(name: String) = if (name in KEYWORDS) "`$name`" else name

        fun lowerCamel(snake: String): String {
            val parts = snake.split('_').filter { it.isNotEmpty() }
            if (parts.isEmpty()) return snake
            return parts.first().replaceFirstChar { it.lowercase() } +
                parts.drop(1).joinToString("") { it.replaceFirstChar { c -> c.uppercase() } }
        }

        fun upperCamel(snake: String): String = lowerCamel(snake).replaceFirstChar { it.uppercase() }
    }
}
